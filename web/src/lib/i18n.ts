export type Lang = keyof typeof I18N
export type TKey = keyof (typeof I18N)['en']

export function translate(lang: Lang, key: TKey | string, vars: Record<string, string | number> = {}) {
  const table = I18N[lang] as Record<string, string>
  const text = table[key] ?? (I18N.en as Record<string, string>)[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}
